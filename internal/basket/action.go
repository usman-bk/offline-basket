package basket

import (
	"errors"
	"fmt"
	"time"
)

// MaxBatch is the largest replay queue the server will accept in one request.
// A phone that has been offline for a week can hold more than this; it sends
// them in order, in several batches, and each batch settles on its own. The
// cap exists so one request cannot pin a connection or a transaction open for
// an unbounded amount of work.
const MaxBatch = 200

// Kind is what an action does to the cart.
type Kind string

const (
	KindAdd    Kind = "add_item"
	KindRemove Kind = "remove_item"
	KindSetQty Kind = "set_qty"
	KindClear  Kind = "clear_cart"
)

// MaxQty is the ceiling on a single line. Marketplace stock is graded and
// mostly one of a kind, so a line asking for 400 of something is a client bug
// rather than a customer.
const MaxQty = 99

// Action is one thing the customer did, recorded on the device at the moment
// they did it, whether or not there was a signal.
//
// ID is generated by the client, not the server. That is the whole basis of
// the replay: the device can retry a batch it never saw a response to, and the
// server recognises every action in it. A server generated id would be unknown
// to the client at the point it needs to retry.
//
// Seq is a Lamport clock, not a position in the queue and not a timestamp. See
// stamp.go for why wall clock time from a phone cannot order anything.
type Action struct {
	ID       string    `json:"id"`
	DeviceID string    `json:"device_id"`
	Seq      uint64    `json:"seq"`
	Kind     Kind      `json:"kind"`
	SKU      string    `json:"sku,omitempty"`
	Qty      int       `json:"qty,omitempty"`
	ClientAt time.Time `json:"client_at"`
}

// Stamp is the position of this action in the merge order.
func (a Action) Stamp() Stamp { return Stamp{Seq: a.Seq, DeviceID: a.DeviceID, ActionID: a.ID} }

var (
	ErrNoID       = errors.New("action has no id")
	ErrNoDevice   = errors.New("action has no device id")
	ErrNoSeq      = errors.New("action has no seq")
	ErrNoSKU      = errors.New("action needs a sku")
	ErrSKUOnClear = errors.New("clear_cart takes no sku")
	ErrQtyRange   = errors.New("qty out of range")
	ErrBatchSize  = fmt.Errorf("batch over %d actions", MaxBatch)
)

// Validate rejects an action the merge could not place in an order, and an
// action whose effect is not expressible. It does not reject an action for an
// unknown SKU: the catalogue moves under the cart, and an item withdrawn while
// the phone was offline is a pricing concern at checkout, not a reason to
// throw away something the customer chose.
func (a Action) Validate() error {
	switch {
	case a.ID == "":
		return ErrNoID
	case a.DeviceID == "":
		return ErrNoDevice
	case a.Seq == 0:
		return ErrNoSeq
	}
	switch a.Kind {
	case KindAdd, KindRemove:
		if a.SKU == "" {
			return ErrNoSKU
		}
		if a.Kind == KindAdd && (a.Qty < 1 || a.Qty > MaxQty) {
			return ErrQtyRange
		}
	case KindSetQty:
		if a.SKU == "" {
			return ErrNoSKU
		}
		if a.Qty < 0 || a.Qty > MaxQty {
			return ErrQtyRange
		}
	case KindClear:
		if a.SKU != "" {
			return ErrSKUOnClear
		}
	default:
		return fmt.Errorf("unknown kind %q", a.Kind)
	}
	return nil
}
